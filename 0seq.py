"""
Список методов, которые чаще всего используются для каждого типа данных:

Для списков (list):

append(x) — добавляет элемент в конец списка.
extend(iterable) — расширяет список, добавляя все элементы из переданного итерируемого объекта.
insert(i, x) — вставляет элемент на указанную позицию в списке.
remove(x) — удаляет первый элемент в списке, равный значению x.
pop([i]) — удаляет элемент по индексу и возвращает его. Если индекс не указан, удаляет и возвращает последний элемент.

Для словарей (dict):

get(key, default=None) — возвращает значение для ключа, если он существует, иначе возвращает default.
items() — возвращает представление всех пар "ключ-значение" в виде кортежей.
keys() — возвращает представление всех ключей словаря.
values() — возвращает представление всех значений в словаре.
update(other) — обновляет словарь, добавляя пары ключ-значение из другого словаря или итерируемого объекта.

Для множеств (set):

add(x) — добавляет элемент в множество.
remove(x) — удаляет элемент из множества. Если элемент отсутствует, вызывает ошибку KeyError.
discard(x) — удаляет элемент из множества, не вызывая ошибку, если элемент отсутствует.
union(*others) — возвращает объединение текущего множества с другими множествами.
intersection(*others) — возвращает пересечение текущего множества с другими множествами.

Для строк (str):

lower() — возвращает строку, переведенную в нижний регистр.
upper() — возвращает строку, переведенную в верхний регистр.
split(sep=None, maxsplit=-1) — разбивает строку на список подстрок, используя разделитель.
replace(old, new, count=-1) — заменяет все вхождения подстроки old на подстроку new.
strip([chars]) — удаляет пробелы или указанные символы с начала и конца строки.
"""