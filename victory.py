"""7. (МОДУЛЬ 4) В проекте создать новый модуль victory.py. Задание
Написать или улучшить программу Викторина из предыдущего дз
(Для тренировки предлагаю не пользоваться никакими библиотеками кроме random)
Есть 10 известных людей и их даты рождения в формате '02.01.1988' ('dd.mm.yyyy') -
предлагаю для тренировки пока использовать строку
Программа выбирает из этих 10-и 5 случайных людей, это можно реализовать с помощью модуля random
 и функции sample
Пример использования sample:
import random
numbers = [1, 2, 3, 4, 5]

# 2 - количество случайных элементов
result = random.sample(numbers, 2)

print(result) # [5, 1]

После того как выбраны 5 случайных людей, предлагаем пользователю ввести их дату рождения
пользователь вводит дату в формате 'dd.mm.yyyy'

Например 03.01.2009, если пользователь ответил неверно, то выводим правильный ответ, но уже в следующем виде: третье января 2009 года, склонением можно пренебречь

В конце считаем количество правильных и неправильных ответов и предлагаем начать снова

Пётр I - 9 июня 1672
Че Гевара - 14 июня 1928
Ленин - 22 апреля 1870
Гоголь - 1 апреля 1809
Достоевский - 11 ноября 1821
Фрида Кало - 6 июля 1907г
Индира Ганди - 19 ноября 1917г
Маргарет Тэтчер - 13 октября 1925г
Диана, принцесса Уэльская - 1 июля 1961г
Элвис Пресли - 8 января 1935г
"""

import random

# Словарь известных людей и их даты рождения
people = {
    "Пётр I": "09.06.1672",
    "Че Гевара": "14.06.1928",
    "Ленин": "22.04.1870",
    "Гоголь": "01.04.1809",
    "Достоевский": "11.11.1821",
    "Фрида Кало": "06.07.1907",
    "Индира Ганди": "19.11.1917",
    "Маргарет Тэтчер": "13.10.1925",
    "Диана, принцесса Уэльская": "01.07.1961",
    "Элвис Пресли": "08.01.1935"
}

# Множество для хранения неправильных ответов
incorrect_answers = set()

# Месяцы для преобразования даты в текст
months = {
    "01": "января", "02": "февраля", "03": "марта", "04": "апреля", "05": "мая",
    "06": "июня", "07": "июля", "08": "августа", "09": "сентября", "10": "октября",
    "11": "ноября", "12": "декабря"
}

while True:
    count_correct = 0
    total_questions = 5  # Общее количество вопросов

    # Выбираем случайных людей (используем sample для уникальности)
    selected_people = random.sample(list(people.items()), total_questions)

    for person, correct_date in selected_people:
        user_input = input(f"Какой год рождения у {person}? Введите в формате 'dd.mm.yyyy': ")

        # Проверяем правильность введенной даты
        if user_input == correct_date:
            count_correct += 1
        else:
            # Преобразование даты в текстовый формат
            day, month, year = correct_date.split(".")
            formatted_date = f"{int(day)} {months[month]} {year} года"
            print(f"Правильный ответ: {formatted_date}")
            incorrect_answers.add(person)  # Добавляем в множество неправильных ответов

    # Подсчет результатов
    count_errors = total_questions - count_correct
    percent_correct = count_correct * 100 / total_questions
    percent_incorrect = count_errors * 100 / total_questions

    # Вывод результатов
    print("\nРезультаты викторины:")
    print(f"Правильных ответов: {count_correct}")
    print(f"Ошибок: {count_errors}")
    print(f"Процент правильных ответов: {int(percent_correct)}%")
    print(f"Процент неправильных ответов: {int(percent_incorrect)}%")

    # Выводим людей с ошибочными ответами
    if incorrect_answers:
        print("Неправильные ответы даны на следующие вопросы:")
        for person in incorrect_answers:
            print(person)
    else:
        print("Поздравляем, все ответы правильные!")

    # Рестарт?
    restart = input("\nХотите ли начать игру сначала? (да/нет): ")
    if restart != "да":
        print("Спасибо за игру!")
        break
